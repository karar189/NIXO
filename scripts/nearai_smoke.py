#!/usr/bin/env python3
"""NEAR AI Cloud smoke test: one completion, verified end to end.

Follows the staged workflow in the official SDK verification guide
(https://github.com/nearai/inference-sdk/blob/main/py/docs/verification-guide.md):

  1. Preflight: fetch Gateway + model attestations, each with a fresh random nonce
     generated by the SDK, and verify them: Intel TDX quote (DCAP), RTMR3 event-log
     replay, MRCONFIGID = sha256(app_compose), nonce + signer bound in report data,
     Gateway TLS key bound in the quote, NVIDIA GPU evidence via NRAS (JWT signature
     and eat_nonce).
  2. Send one chat completion with the canonical model id and x-no-aliasing,
     keeping the exact request and response bytes.
  3. Fetch the response signature and verify it over those exact bytes against
     the matching *preflight* signer (provider_tee -> model report, gateway -> Gateway).

Nothing is faked: a check that cannot run is reported as SKIPPED, never PASS, and
the exit code is 0 only when every check passed.

Usage:  NEARAI_API_KEY=... python scripts/nearai_smoke.py [model]
Needs:  pip install nearai-inference-sdk==0.3.0   (Python >= 3.12)

Privacy: this script prints only check results, never the prompt or response body.
"""

from __future__ import annotations

import asyncio
import json
import os
import sys
import time
from dataclasses import dataclass, field

import httpx
from nearai_inference_sdk import (
    AttestationClient,
    ModelAttestationPolicy,
    create_pinned_tls_client,
    find_model_attestations_for_signature,
    verify_gateway_attestation,
    verify_gateway_response,
    verify_model_attestation,
    verify_model_response,
)

BASE_URL = "https://cloud-api.near.ai/v1"
DEFAULT_MODEL = "z-ai/glm-5.3-flash"
SIGNING_ALGO = "ecdsa"  # same explicit algo for both attestation fetches and the signature fetch
SIGNATURE_RETRIES = 5  # bounded retry: a signature can take a moment to be recorded


@dataclass
class Report:
    checks: list[dict] = field(default_factory=list)

    def add(self, name: str, status: str, detail: str = "") -> None:
        self.checks.append({"check": name, "status": status, "detail": detail})
        mark = {"PASS": "✓", "FAIL": "✗", "SKIPPED": "-"}[status]
        print(f"  {mark} {status:<7} {name}" + (f"  ({detail})" if detail else ""), flush=True)

    @property
    def ok(self) -> bool:
        return bool(self.checks) and all(c["status"] == "PASS" for c in self.checks)


async def main(model: str) -> int:
    api_key = os.environ.get("NEARAI_API_KEY") or None
    r = Report()
    started = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    print(f"NEAR AI Cloud smoke test  model={model}  signing_algo={SIGNING_ALGO}  at={started}")

    async with httpx.AsyncClient(timeout=60) as http:
        att = AttestationClient(api_key, base_url=BASE_URL, http_client=http)

        # 1a. Gateway evidence (fresh nonce, quote-bound TLS identity).
        print("\n1) Preflight attestation")
        try:
            fg = await att.fetch_gateway_attestation(signing_algo=SIGNING_ALGO)
            print(f"     gateway nonce: {fg.client_binding.nonce}")
            gw = await verify_gateway_attestation(fg.attestation, fg.client_binding)
            r.add("gateway: TDX quote (DCAP), RTMR3, MRCONFIGID, nonce + signer binding", "PASS",
                  f"tcb={gw.tcb_status} signer={gw.signer.signing_address}")
            tls_ok = gw.tls_binding.kind == "attested"
            r.add("gateway: TLS key bound in quote", "PASS" if tls_ok else "FAIL", f"kind={gw.tls_binding.kind}")
        except Exception as e:  # noqa: BLE001 - every failure is reported, never swallowed
            r.add("gateway attestation", "FAIL", f"{type(e).__name__}: {e}")
            gw = None

        # 1b. Model evidence: verify EVERY returned candidate, GPU evidence required.
        verified_models = []
        try:
            fm = await att.fetch_model_attestations(model, signing_algo=SIGNING_ALGO)
            print(f"     model nonce:   {fm.client_binding.nonce}")
            if not fm.attestations:
                r.add("model: attestation candidates returned", "FAIL", "model_attestations[] empty")
            else:
                r.add("model: attestation candidates returned", "PASS", f"{len(fm.attestations)} candidate(s)")
            policy = ModelAttestationPolicy(gpu_evidence="required")
            for i, a in enumerate(fm.attestations):
                try:
                    v = await verify_model_attestation(a, fm.client_binding, policy=policy)
                    verified_models.append(v)
                    r.add(f"model[{i}]: TDX quote (DCAP), RTMR3, MRCONFIGID, nonce + signer binding", "PASS",
                          f"tcb={v.tcb_status} signer={v.signer.signing_address}")
                    r.add(f"model[{i}]: NVIDIA GPU evidence (NRAS JWT + eat_nonce)",
                          "PASS" if v.gpu_evidence == "verified" else "FAIL", v.gpu_evidence)
                except Exception as e:  # noqa: BLE001
                    r.add(f"model[{i}]: attestation", "FAIL", f"{type(e).__name__}: {e}")
        except Exception as e:  # noqa: BLE001
            r.add("model attestation fetch", "FAIL", f"{type(e).__name__}: {e}")

        # 2 + 3. Completion and its response signature (needs an API key).
        print("\n2) Completion + 3) response signature")
        if not api_key:
            r.add("completion sent with exact bytes retained", "SKIPPED", "NEARAI_API_KEY not set")
            r.add("response signature verified against preflight signer", "SKIPPED", "NEARAI_API_KEY not set")
        elif gw is None or not verified_models:
            r.add("completion", "SKIPPED", "preflight failed; not sending a prompt to unverified infra")
        else:
            request_body = json.dumps(
                {"model": model, "messages": [{"role": "user", "content": "Reply with the word ok."}],
                 "stream": False},
                separators=(",", ":"),
            ).encode()
            headers = {"Authorization": f"Bearer {api_key}", "Content-Type": "application/json",
                       "Accept-Encoding": "identity", "x-no-aliasing": "true"}
            try:
                # Pinned to the TLS key the Gateway quote attested.
                async with create_pinned_tls_client(gw.tls_binding.spki_fingerprint) as pinned:
                    resp = await pinned.post(f"{BASE_URL}/chat/completions", content=request_body, headers=headers)
                response_body = resp.content  # exact bytes, before any JSON parsing
                if resp.status_code != 200:
                    r.add("completion", "FAIL", f"HTTP {resp.status_code}: {response_body[:200]!r}")
                else:
                    chat_id = json.loads(response_body)["id"]
                    r.add("completion sent with exact bytes retained", "PASS", f"id={chat_id}")
                    sig = None
                    for attempt in range(SIGNATURE_RETRIES):
                        try:
                            sig = await att.fetch_completion_signature(chat_id, signing_algo=SIGNING_ALGO)
                            break
                        except Exception as e:  # noqa: BLE001
                            last = e
                            await asyncio.sleep(1 + attempt)
                    if sig is None:
                        r.add("response signature fetched", "FAIL", f"{type(last).__name__}: {last}")
                    else:
                        r.add("response signature fetched", "PASS", f"kind={sig.kind}")
                        try:
                            if sig.kind == "provider_tee":
                                matches = find_model_attestations_for_signature(verified_models, sig)
                                if not matches:
                                    raise RuntimeError("signer matches no verified preflight model report")
                                verify_model_response(request_body, response_body, sig, matches[0])
                                detail = f"provider_tee signer={sig.signer.signing_address} (model TEE)"
                            elif sig.kind == "gateway":
                                verify_gateway_response(request_body, response_body, sig, gw)
                                detail = f"gateway signer={sig.signer.signing_address} (gateway TEE, not model)"
                            else:
                                raise RuntimeError(f"unknown signature kind {sig.kind!r}")
                            r.add("response signature verified against preflight signer", "PASS", detail)
                        except Exception as e:  # noqa: BLE001
                            r.add("response signature verified against preflight signer", "FAIL",
                                  f"{type(e).__name__}: {e}")
            except Exception as e:  # noqa: BLE001
                r.add("completion", "FAIL", f"{type(e).__name__}: {e}")

    print(f"\nRESULT: {'VERIFIED' if r.ok else 'NOT VERIFIED'}  "
          f"({sum(c['status'] == 'PASS' for c in r.checks)} pass, "
          f"{sum(c['status'] == 'FAIL' for c in r.checks)} fail, "
          f"{sum(c['status'] == 'SKIPPED' for c in r.checks)} skipped)")
    return 0 if r.ok else 1


if __name__ == "__main__":
    sys.exit(asyncio.run(main(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_MODEL)))
